function width(text, cell, gap) {
  text = String(text || "")
  if (text.length === 0) return 0
  return text.length * cell + (text.length - 1) * gap
}

function draw(ctx, text, x, y, cell, gap, lineWidth, color) {
  text = String(text || "")
  ctx.save()
  ctx.strokeStyle = color
  ctx.lineWidth = lineWidth
  ctx.lineCap = "round"
  ctx.lineJoin = "round"

  var pad = cell * 0.16
  var inner = cell - pad * 2
  var cx = x

  for (var i = 0; i < text.length; i++) {
    var glyph = GLYPHS[text.charAt(i).toUpperCase()]
    if (glyph) {
      for (var s = 0; s < glyph.length; s++) {
        var poly = glyph[s]
        ctx.beginPath()
        for (var p = 0; p < poly.length; p++) {
          var px = cx + pad + poly[p][0] * inner
          var py = y + pad + poly[p][1] * inner
          if (p === 0) ctx.moveTo(px, py)
          else ctx.lineTo(px, py)
        }
        ctx.stroke()
      }
    }
    cx += cell + gap
  }

  ctx.restore()
}
